import {test,expect} from '@playwright/test'
import {execFileSync} from 'node:child_process'
import path from 'node:path'

test('arrangements preserve source, synchronize comparison, save guidance and export selected notes',async({page,request})=>{
 test.setTimeout(120000)
 const root=path.resolve('..')
 execFileSync(path.join(root,'.venv/Scripts/python.exe'),['-c',"from backend.tests.test_arrangements import fixture; from backend import store; store.setup(); store.piece_save(fixture())"],{cwd:root,env:{...process.env,PIANO_DATA_DIR:path.join(root,'data/browser-tests')},timeout:30000})
 const original=await (await request.get('/api/pieces/arrangementfixture')).json()
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByRole('button',{name:'My pieces',exact:true}).click()
 await page.locator('[data-piece-id="arrangementfixture"] .library-piece').click()
 await page.getByRole('button',{name:'Simplify arrangement',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Simplify arrangement',exact:true})
 await dialog.getByRole('button',{name:'Melody only',exact:true}).click()
 await dialog.getByRole('button',{name:'Generate & save arrangement',exact:true}).click()
 await expect(dialog.getByRole('heading',{name:'Playing demands',exact:true})).toBeVisible({timeout:30000})
 const first=await page.getByRole('combobox',{name:'Selected arrangement',exact:true}).inputValue()
 const saved=await (await request.get(`/api/pieces/arrangementfixture/arrangements/${first}`)).json()
 expect(saved.performance.notes).toHaveLength(8)
 expect(saved.sourcePerformance.notes).toHaveLength(original.notes.length)
 await dialog.getByRole('button',{name:'Close arrangement settings'}).click()
 await expect(page.getByLabel('Active difficulty',{exact:true})).toHaveText('Melody only')
 await expect(page.locator('[data-performance-notes="m0"]').first()).toBeAttached({timeout:20000})
 await expect(page.locator('[data-performance-notes="upper2"]')).toHaveCount(0)
 await page.getByRole('combobox',{name:'Playback speed',exact:true}).selectOption('0.5')
 await page.getByRole('slider',{name:'Playback position',exact:true}).fill('1.2')
 const comparison=page.getByRole('group',{name:'Listening comparison'})
 await comparison.getByRole('button',{name:'Full transcription',exact:true}).click()
 await expect(page.getByRole('slider',{name:'Playback position',exact:true})).toHaveValue('1.2')
 await expect(page.getByRole('combobox',{name:'Playback speed',exact:true})).toHaveValue('0.5')
 await expect(page.locator('[data-performance-notes="upper2"]').first()).toBeAttached({timeout:20000})
 await page.getByRole('button',{name:'Play',exact:true}).click()
 await comparison.getByRole('button',{name:'Selected arrangement',exact:true}).click()
 await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await page.getByRole('button',{name:'Simplify arrangement',exact:true}).click()
 await dialog.getByRole('combobox',{name:'Review source note',exact:true}).selectOption('m0')
 await dialog.getByRole('combobox',{name:'Source note musical role',exact:true}).selectOption('melody')
 await dialog.getByRole('checkbox',{name:'Protect this melody note',exact:true}).check()
 await dialog.getByRole('button',{name:'Save melody guidance',exact:true}).click()
 await expect(dialog.getByText(/Based on an older source revision/)).toBeVisible()
 expect((await (await request.get(`/api/pieces/arrangementfixture/arrangements/${first}`)).json()).performance).toEqual(saved.performance)
 await dialog.getByRole('button',{name:'Refresh as new version',exact:true}).click()
 await expect.poll(()=>page.getByRole('combobox',{name:'Selected arrangement',exact:true}).inputValue()).not.toBe(first)
 const refreshed=await page.getByRole('combobox',{name:'Selected arrangement',exact:true}).inputValue()
 await dialog.getByRole('button',{name:'Close arrangement settings'}).click()
 await page.reload()
 await page.getByRole('button',{name:'My pieces',exact:true}).click()
 await page.locator('[data-piece-id="arrangementfixture"] .library-piece').click()
 await expect(page.getByRole('combobox',{name:'Selected arrangement',exact:true})).toHaveValue(refreshed)
 await page.getByRole('button',{name:'Practice settings',exact:true}).click()
 const exportLink=page.getByRole('link',{name:'MusicXML',exact:true})
 expect(await exportLink.getAttribute('href')).toContain(`arrangementId=${refreshed}`)
 const xml=await request.get((await exportLink.getAttribute('href'))!)
 expect(xml.ok()).toBe(true)
 await page.getByRole('button',{name:'Close dialog',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Simplify arrangement',exact:true}).click()
 await dialog.getByText('Advanced arrangement settings',{exact:true}).click()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'test-results/arrangement-mobile.png',fullPage:true})
 const source=await (await request.get('/api/pieces/arrangementfixture')).json()
 expect(source.raw).toEqual(original.raw);expect(source.edits).toEqual(original.edits)
 expect(errors).toEqual([])
})
