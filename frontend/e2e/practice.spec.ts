import {test,expect} from '@playwright/test'
test('demo playback, seek, loop, score and mobile layouts',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Windowlight'})).toBeVisible()
 await expect(page.locator('.score-render svg').first()).toBeVisible({timeout:20000})
 await page.getByRole('button',{name:'Play',exact:true}).click()
 await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible()
 await expect.poll(async()=>+(await page.getByRole('slider',{name:'Playback position'}).inputValue())).toBeGreaterThan(1)
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 const paused=+(await page.getByRole('slider',{name:'Playback position'}).inputValue())
 await page.waitForTimeout(250)
 expect(+(await page.getByRole('slider',{name:'Playback position'}).inputValue())).toBeCloseTo(paused,1)
 await page.getByRole('slider',{name:'Playback position'}).fill('10')
 await expect.poll(async()=>+(await page.getByRole('slider',{name:'Playback position'}).inputValue())).toBe(10)
 await page.getByRole('button',{name:'Toggle loop'}).click()
 await page.getByRole('slider',{name:'Loop start',exact:true}).fill('10')
 await page.getByRole('slider',{name:'Loop end',exact:true}).fill('11')
 await page.getByRole('button',{name:'Play',exact:true}).click();await page.waitForTimeout(2400)
 const looped=+(await page.getByRole('slider',{name:'Playback position'}).inputValue());expect(looped).toBeGreaterThanOrEqual(10);expect(looped).toBeLessThan(11.1)
 await page.getByRole('button',{name:'Pause',exact:true}).click();await page.getByRole('button',{name:'Toggle loop'}).click()
 for(const [width,height] of [[1440,1000],[390,844],[844,390],[768,1024],[1024,768]]){
  await page.setViewportSize({width,height});await page.waitForTimeout(500)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await expect(page.getByRole('button',{name:'Play',exact:true})).toBeVisible()
  expect(+(await page.locator('.score-render').getAttribute('data-cursor-beat')??0)).toBeGreaterThanOrEqual(16)
  await expect(page.locator('[data-performance-notes]').first()).toBeAttached()
  const canvas=await page.locator('canvas').boundingBox(),transport=await page.locator('.transport').boundingBox()
  expect(canvas!.y+canvas!.height).toBeLessThanOrEqual(transport!.y+1)
  await page.screenshot({path:`test-results/layout-${width}x${height}.png`,fullPage:true})
 }
 expect(errors).toEqual([])
})
test('settings, MIDI import, corrections and exports',async({page,request})=>{
 await page.goto('/');await page.getByRole('button',{name:'Practice settings',exact:true}).click()
 await page.getByRole('combobox',{name:'Choose a note to correct'}).selectOption({index:1})
 await expect(page.getByRole('dialog',{name:'Correct note'})).toBeVisible()
 await page.getByRole('spinbutton',{name:'MIDI pitch'}).fill('49');await page.getByRole('button',{name:'Save correction',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Correct note'})).toHaveCount(0)
 const midi=await request.get('/api/pieces/demo/export/midi');expect(midi.ok()).toBe(true)
 await page.getByRole('button',{name:'New piece',exact:true}).click();await page.getByRole('button',{name:'MIDI',exact:true}).click()
 await page.locator('input[type=file]').setInputFiles({name:'Browser test.mid',mimeType:'audio/midi',buffer:await midi.body()})
 await expect(page.getByRole('heading',{name:'Browser test',exact:true})).toBeVisible({timeout:20000})
 await expect(page.locator('.score-render svg').first()).toBeVisible()
})
